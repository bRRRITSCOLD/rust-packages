//! Vendors every canonical Lucide icon from `lucide-static` at the version core-react pins,
//! and generates `core_gpui::icons`' `IconName` enum.
//!
//! Canonical means the keys of `icon-nodes.json`: deprecated aliases (`lucide-static` ships
//! them as extra SVGs) are left out.

use std::path::Path;

use anyhow::{Context, Result};

use super::{extract_where, npm_tarball, write};

const PACKAGE: &str = "lucide-static";
/// The vendored SVGs, one `<name>.svg` per icon, plus Lucide's `LICENSE`.
pub const ICONS_DIR: &str = "crates/core-gpui/icons";
pub const GENERATED_FILE: &str = "crates/core-gpui/src/icons/generated.rs";

/// Downloads `lucide-static@version`, replaces the vendored SVGs and regenerates the enum.
pub fn vendor(root: &Path, version: &str) -> Result<()> {
    let (resolved, bytes) = npm_tarball(PACKAGE, version)?;
    let files = extract_where(&bytes, |path| {
        path == "package/icon-nodes.json"
            || path == "package/LICENSE"
            || (path.starts_with("package/icons/") && path.ends_with(".svg"))
    })?;
    let nodes: serde_json::Value = serde_json::from_slice(
        files
            .get("package/icon-nodes.json")
            .context("lucide-static has no icon-nodes.json")?,
    )?;
    let names: Vec<String> = nodes
        .as_object()
        .context("icon-nodes.json is not an object")?
        .keys()
        .cloned()
        .collect();

    let dir = root.join(ICONS_DIR);
    if dir.exists() {
        for entry in std::fs::read_dir(&dir)? {
            let path = entry?.path();
            if path.extension().is_some_and(|ext| ext == "svg") {
                std::fs::remove_file(path)?;
            }
        }
    }
    for name in &names {
        let svg = files
            .get(&format!("package/icons/{name}.svg"))
            .with_context(|| format!("lucide-static has no icons/{name}.svg"))?;
        write(&dir.join(format!("{name}.svg")), std::str::from_utf8(svg)?)?;
    }
    let license = files
        .get("package/LICENSE")
        .context("lucide-static has no LICENSE")?;
    write(&dir.join("LICENSE"), std::str::from_utf8(license)?)?;
    regenerate(root, &resolved)
}

/// Regenerates the enum from the vendored SVGs.
pub fn regenerate(root: &Path, version: &str) -> Result<()> {
    let names = names_on_disk(root)?;
    write(&root.join(GENERATED_FILE), &generate(&names, version))
}

/// The vendored icon names, sorted.
pub fn names_on_disk(root: &Path) -> Result<Vec<String>> {
    let mut names = Vec::new();
    for entry in std::fs::read_dir(root.join(ICONS_DIR))? {
        let path = entry?.path();
        if path.extension().is_some_and(|ext| ext == "svg") {
            let stem = path.file_stem().context("an SVG without a name")?;
            names.push(stem.to_string_lossy().into_owned());
        }
    }
    names.sort();
    Ok(names)
}

/// The `IconName` module for these icon names.
pub fn generate(names: &[String], version: &str) -> String {
    let mut out = format!(
        "// @generated by `cargo xtask tokens` from lucide-static@{version}. Do not edit.\n\n"
    );
    out.push_str(
        "/// Every canonical Lucide icon core-react ships, named as lucide-react names it\n\
         /// (without the `Icon` suffix). `<&str>::from` gives the variant name: the drift\n\
         /// manifest's `<Name>Icon` is that plus `Icon`.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, strum::IntoStaticStr)]\n\
         pub enum IconName {\n",
    );
    for name in names {
        out.push_str(&format!("    /// `{name}`\n    {},\n", pascal(name)));
    }
    out.push_str("}\n\nimpl IconName {\n");
    out.push_str("    /// Every icon, in file-name order.\n    pub const ALL: &[IconName] = &[\n");
    for name in names {
        out.push_str(&format!("        IconName::{},\n", pascal(name)));
    }
    out.push_str("    ];\n\n");
    out.push_str(
        "    /// The Lucide file name, without `.svg`.\n    pub const fn file_name(self) -> &'static str {\n        match self {\n",
    );
    for name in names {
        out.push_str(&format!(
            "            IconName::{} => {name:?},\n",
            pascal(name)
        ));
    }
    out.push_str("        }\n    }\n\n");
    out.push_str(
        "    /// The SVG source.\n    pub const fn svg(self) -> &'static [u8] {\n        match self {\n",
    );
    for name in names {
        out.push_str(&format!(
            "            IconName::{} => include_bytes!(\"../../icons/{name}.svg\"),\n",
            pascal(name)
        ));
    }
    out.push_str("        }\n    }\n}\n");
    out
}

/// lucide-react's export name, without `Icon`: `arrow-down-0-1` → `ArrowDown01`.
fn pascal(name: &str) -> String {
    name.split('-')
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tokens::workspace_root;

    mod pascal {
        use super::*;

        #[test]
        fn should_match_lucide_react_export_names() {
            assert_eq!(pascal("a-arrow-down"), "AArrowDown");
            assert_eq!(pascal("arrow-down-0-1"), "ArrowDown01");
            assert_eq!(pascal("plus"), "Plus");
        }
    }

    mod generate {
        use super::*;

        #[test]
        fn should_emit_one_variant_and_arm_per_icon() {
            let out = generate(&["arrow-down-0-1".into(), "plus".into()], "1.0.0");
            assert!(out.contains("    ArrowDown01,\n"));
            assert!(out.contains("IconName::Plus => \"plus\","));
            assert!(out.contains("IconName::Plus => include_bytes!(\"../../icons/plus.svg\"),"));
        }

        /// The drift manifest names icons `<Variant>Icon` from strum, with no case transform.
        #[test]
        fn should_give_each_icon_its_variant_name_as_a_static_str() {
            let out = generate(&["plus".into()], "1.0.0");
            assert!(out.contains("strum::IntoStaticStr)]\npub enum IconName"));
        }
    }

    /// Staleness: a hand edit, an added or removed SVG, or a forgotten regeneration fails here.
    mod sourcegen {
        use super::*;

        #[test]
        fn should_match_the_checked_in_icon_enum() {
            let root = workspace_root();
            let pin = crate::tokens::read_pin(&root).unwrap();
            let names = names_on_disk(&root).unwrap();
            let checked_in = std::fs::read_to_string(root.join(GENERATED_FILE)).unwrap();
            assert!(
                generate(&names, &pin.lucide) == checked_in,
                "{GENERATED_FILE} is stale or hand-edited: run `cargo xtask tokens generate`"
            );
        }
    }
}
